"""Regenerate src/cabac_tables.rs from frame_dedup/cabac_tables.json.

Usage: python port/gen_cabac_tables.py > src/cabac_tables.rs
"""
import json
import os

here = os.path.dirname(os.path.abspath(__file__))
t = json.load(open(os.path.join(here, '..', 'frame_dedup', 'cabac_tables.json')))


def arr(rows, per=8):
    out = []
    for i in range(0, len(rows), per):
        out.append('    ' + ' '.join(f'{r},' for r in rows[i:i + per]))
    return '\n'.join(out)


print('//! CABAC tables, generated by port/gen_cabac_tables.py from frame_dedup/cabac_tables.json.')
print('//! Do not edit by hand.\n')
print('pub const RANGE_LPS: [[u8; 4]; 64] = [')
print(arr([f'[{", ".join(map(str, r))}]' for r in t['rangeTabLPS']], 4))
print('];\n')
print('pub const TRANS_LPS: [u8; 64] = [')
print(arr([str(x) for x in t['transIdxLPS']], 16))
print('];\n')
print('pub const LAST_8X8: [u8; 63] = [')
print(arr([str(x) for x in t['last_coeff_flag_offset_8x8']], 16))
print('];\n')
print('/// (m, n) pairs per context index for I slices.')
print('pub const INIT_I: [(i8, i8); 1024] = [')
print(arr([f'({m}, {n})' for m, n in t['init_I']], 8))
print('];\n')
print('/// (m, n) pairs per context index for P and B slices, by cabac_init_idc.')
print('pub const INIT_PB: [[(i8, i8); 1024]; 3] = [')
for tab in t['init_PB']:
    print('    [')
    print(arr([f'({m}, {n})' for m, n in tab], 8).replace('\n    ', '\n    ').replace('    ', '        ', 1))
    print('    ],')
print('];')
